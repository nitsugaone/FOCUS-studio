import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const start=html.indexOf('      function summarizeRatings('),end=html.indexOf('      function renderInsights()',start);
assert.ok(start>=0 && end>start);
const summarize=new Function('SCENES',html.slice(start,end)+'return summarizeRatings;')({rain:{},ocean:{},space:{},speech:{}});
const now=Date.parse('2026-10-22T12:00:00Z');
const make=(scene,rating=4,days=1)=>({scene,rating,date:new Date(now-days*86400000).toISOString(),minutes:25,distractions:'low'});
const records=[...Array.from({length:3},()=>make('rain',5)),...Array.from({length:3},()=>make('ocean',4)),make('space',2,20),make('rain',3,40)];
const original=JSON.stringify(records);
let result=summarize(records,7,'all',now);
assert.equal(result.count,6);
assert.equal(result.average,4.5);
assert.equal(result.best.scene,'rain');
assert.equal(result.groups[0].count,3);
assert.equal(result.groups[0].lowDistractions,3);
assert.equal(summarize(records,30,'all',now).count,7);
assert.equal(summarize(records,0,'all',now).count,8);
assert.equal(summarize(records,7,'rain',now).count,3);
assert.equal(summarize(records,7,'rain',now).best,null);
assert.equal(JSON.stringify(records),original,'Filters never mutate saved records');
assert.equal(summarize([],7,'all',now).count,0);
assert.equal(summarize(null,7,'all',now).count,0);
const invalid=[null,{},make('unknown'),{...make('rain'),rating:6},{...make('rain'),rating:2.5},{...make('rain'),minutes:-1},{...make('rain'),date:'bad'},{...make('rain'),distractions:'invalid'},make('rain',5,-1)];
assert.equal(summarize(invalid,0,'all',now).count,0);
assert.equal(summarize([make('rain',4,7)],7,'all',now).count,1,'Period boundary is inclusive');
assert.equal(summarize([make('rain',4,7.01)],7,'all',now).count,0);
const tied=[...Array.from({length:3},()=>make('rain',4)),...Array.from({length:3},()=>make('ocean',4))];
assert.equal(summarize(tied,7,'all',now).best,null);
assert.equal(summarize([...Array.from({length:2},()=>make('rain',5)),...Array.from({length:3},()=>make('ocean',4))],7,'all',now).best,null,'Insufficient samples are not ranked');
assert.equal(summarize(Array.from({length:250},()=>make('rain')),7,'all',now).count,200);
console.log('PASS: rating averages, period and scene filters, sample thresholds, ties, corrupt data and immutability');
